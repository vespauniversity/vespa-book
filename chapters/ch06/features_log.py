"""Log the engine's own rank features for every judged (query, product) pair -
the feature log chapter 7 learns a ranking function from.

Not a measurement: an artefact this chapter provides to the next. For every
judged pair of `--split`, this
asks the `features` profile (rerank mode: scoring restricted to judged ids, so
retrieval never enters the comparison) for its `match-features`, and writes
one CSV row per pair.

Two arms, in order, because restricting a query to judged ids does not mean
every judged id is still a *candidate* - the union YQL (`userQuery() or
nearestNeighbor(...)`) still has to select it first, and a judged product with
no matching term and outside the vector's nearest neighbours never becomes a
candidate no matter what `recall` says:

  **union**   the same union request every measurement in this chapter sends
              (`evaluate.build_request("hybrid", ...)`, plus this profile's
              `qt` input), restricted with `recall` to this query's judged
              ids. `retrieved = 1` for whatever it finds.
  **direct**  `select id from product where true`, restricted with `recall`
              to whatever the union arm above did not find. This still runs
              the deployed rank profile and gets its real feature values -
              zero because there genuinely was no lexical or vector match is
              a fact the profile computes, not one this script invents -
              `retrieved = 0` for these.

A judged id neither arm returns (deleted from the corpus after the build
recorded it - not expected, checked and reported if it happens) gets a
zero-feature row rather than being silently dropped, because
the pair exists in `judgements_<split>.csv` and a learner needs a row for it
even when no arm has anything to say.

**Feature list from the profile, not a copy of it**: two lists that have to
agree will stop agreeing, and the profile is what the engine reads.

**The CSV is a build artefact**: `builds/<build>/features/features-<split>.csv`,
gitignored under `/builds/` and regenerated by this command, not committed.
The JSON report via `--out` is what's committed, under `expected/`.

    .venv/bin/python chapters/ch06/features_log.py --split train \\
        --out chapters/ch06/expected/features-train.json
    .venv/bin/python chapters/ch06/features_log.py --split validation \\
        --out chapters/ch06/expected/features-validation.json
    .venv/bin/python chapters/ch06/features_log.py --split test \\
        --out chapters/ch06/expected/features-test.json

Three invocations, one per split - nothing here tunes anything, train is for
ch7 to learn from and validation / test are for ch7 to evaluate on.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "shared" / "tools"))

import builds                       # noqa: E402
import deployed                     # noqa: E402
import gains                        # noqa: E402
import hostinfo                     # noqa: E402
from evaluate import QUERY_PREFIX, build_request, recall_clause, add_reranker_inputs  # noqa: E402
from query import Vespa             # noqa: E402

PROFILE = "features"


def _features_from_profile() -> tuple[str, ...]:
    """The feature list comes from the rank profile, not from a copy of it,
    read from this chapter's own deployed profile."""
    path = (Path(__file__).resolve().parent / "app" / "schemas" / "product" /
            "features.profile")
    text = path.read_text()
    body = text[text.index("match-features {"):]
    out = []
    for line in body.splitlines()[1:]:
        line = line.strip()
        if line.startswith("#") or not line:
            continue
        if line == "}":
            break
        out.append(line)
    return tuple(out)


FEATURES = _features_from_profile()


def repo_relative(path: Path) -> str:
    """A path for the committed report: relative to the repository root when it
    lies under it (`builds/<build>/features/...`), so the report does not carry
    one machine's home directory; any other path as given."""
    try:
        return str(Path(path).relative_to(builds.ROOT))
    except ValueError:
        return str(path)


def _labels(build: Path, split: str) -> dict[str, dict[str, str]]:
    """query id -> {product id: ESCI label letter}, straight from the build's
    own judgements CSV - it carries the label alongside the gain
    (`query_id,document_id,label,gain,ordinal`), so no lookup into a parquet
    cache is needed."""
    out: dict[str, dict[str, str]] = {}
    with (build / f"judgements_{split}.csv").open() as fh:
        for row in csv.DictReader(fh):
            out.setdefault(row["query_id"], {})[row["document_id"]] = \
                gains.normalise(row["label"])
    return out


# Every query-side input the `features` profile declares, and the embedder
# that fills it. `qt` is ColBERT's query tokens (for `max_sim`), `qt_cross`
# the cross-encoder's (for `cross_logit`). Until 2026-09-23 this dict held
# `qt` only: the profile's `cross_logit` was then computed against a
# zero-filled `qt_cross` - Vespa fills a declared query tensor the request does
# not supply with zeros and says nothing - so the 56th column of every log
# this tool wrote before that date is the cross-encoder scoring an *empty*
# query against the document (chapter 7 found it: no signal by label, and a
# model trained on it disagreed with the engine by a constant). `_check_inputs`
# below is the guard that failure earned.
RERANKER_INPUTS = {"qt": "colbert", "qt_cross": "tokenizer"}


def _embed_qt(text: str) -> dict[str, str]:
    return add_reranker_inputs({}, text, RERANKER_INPUTS)


def profile_inputs(profile_path) -> list[str]:
    """The `query(...)` names a rank profile's `inputs { }` block declares."""
    import re
    text = open(profile_path).read()
    # up to the first line holding only the closing brace: a declared type
    # such as `tensor<float>(querytoken{}, v[128])` has braces of its own
    m = re.search(r"inputs\s*\{(.*?)\n\s*\}", text, re.S)
    return re.findall(r"query\((\w+)\)", m.group(1)) if m else []


def check_inputs(request: dict, declared: list[str]) -> None:
    """Refuse a logging request that leaves one of the profile's declared
    inputs unset: the engine would fill it with zeros and log a feature that
    looks like a number and is not one."""
    missing = [n for n in declared if f"input.query({n})" not in request]
    if missing:
        raise SystemExit(f"the logging request does not set input.query({', '.join(missing)}), "
                         f"which the profile declares; the engine would zero-fill "
                         f"them silently and every feature that reads them would be logged wrong")


def union_request(text: str, judged_ids, hits: int) -> dict:
    request = build_request("hybrid", text, hits)
    request.update(_embed_qt(text))
    request["recall"] = recall_clause(sorted(judged_ids))
    return request


def direct_request(text: str, judged_ids) -> dict:
    """Fetch these ids by id alone, bypassing the union's own matching, so a
    judged id the union arm could not select as a candidate still gets the
    profile's real feature values instead of a row this script invented."""
    request = {"yql": "select id from product where true",
              "recall": recall_clause(sorted(judged_ids))}
    request["input.query(q)"] = f'embed(embedder, "{QUERY_PREFIX}{text}")'
    request.update(_embed_qt(text))
    return request


def collect(app: Vespa, queries: dict[str, str], labels: dict[str, dict[str, str]],
            declared_inputs: list[str] | None = None,
           *, progress_every: int = 200, out=sys.stderr
           ) -> tuple[list[dict], int]:
    """Every judged pair's row. Returns `(rows, retrieved_by_union)`."""
    rows: list[dict] = []
    retrieved_by_union = 0
    ids = sorted(queries)
    for n, qid in enumerate(ids, 1):
        judged = labels.get(qid, {})
        if not judged:
            continue
        text = queries[qid]
        seen: dict[str, dict[str, float]] = {}
        request = union_request(text, judged, len(judged))
        if declared_inputs is not None:
            check_inputs(request, declared_inputs)   # no zero-filled input, every query
        r = app.query(ranking=PROFILE, hits=len(judged), **request)
        for hit in r.hits:
            pid = hit.fields.get("id", "")
            if pid in judged:
                seen[pid] = hit.features

        missing = [pid for pid in judged if pid not in seen]
        direct_found: dict[str, dict[str, float]] = {}
        if missing:
            r2 = app.query(ranking=PROFILE, hits=len(missing),
                          **direct_request(text, missing))
            for hit in r2.hits:
                pid = hit.fields.get("id", "")
                if pid in missing:
                    direct_found[pid] = hit.features

        still_missing = 0
        for pid, label in judged.items():
            if pid in seen:
                retrieved_by_union += 1
                feats = seen[pid]
                retrieved = 1
            elif pid in direct_found:
                feats = direct_found[pid]
                retrieved = 0
            else:
                still_missing += 1
                feats = {}
                retrieved = 0
            rows.append({"query_id": qid, "product_id": pid, "label": label,
                        "retrieved": retrieved,
                        **{k: float(feats.get(k, 0.0)) for k in FEATURES}})
        if still_missing:
            print(f"  warning: {qid} has {still_missing} judged id(s) neither "
                 f"arm returned at all (not in the deployed index)",
                 file=out)
        if progress_every and n % progress_every == 0:
            print(f"  {n:,}/{len(ids):,} queries", file=out, flush=True)
    return rows, retrieved_by_union


def features_log_block(reports: list[dict]) -> str:
    """One row per split-run, as the finished block for the page."""
    out = ["| split | queries | pairs | retrieved-by-union | E | S | C | I | "
          "columns | sha256 |",
          "|---|---|---|---|---|---|---|---|---|---|"]
    for r in reports:
        counts = r["label_counts"]
        out.append(
            f"| {r['split']} | {r['queries']:,} | {r['pairs']:,} | "
            f"{r['retrieved_by_union']:,} | {counts.get('E', 0):,} | "
            f"{counts.get('S', 0):,} | {counts.get('C', 0):,} | "
            f"{counts.get('I', 0):,} | {len(r['columns'])} | "
            f"{r['csv_sha256'][:12]} |")
    return "\n".join(out) + "\n"


# A dict, not a bare call: one entry today, but `--block` is read through it
# rather than printed unconditionally - `chapters/ch05/wider_net.py`'s
# `--block` is accepted and never looked at again, an accepted-but-ignored
# flag this file does not repeat.
BLOCKS = {"features-log": features_log_block}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--split", choices=builds.SPLITS, default=None,
                    help="no default: train / validation / test are three "
                         "separate invocations, never inferred (required "
                         "unless --from re-renders a block, which reads its "
                         "splits from the reports themselves)")
    ap.add_argument("--build", type=Path, default=None)
    ap.add_argument("--limit", type=int, default=None,
                    help="how many queries; default is every query in the "
                         "split (a smoke pass uses this, a real run does not)")
    ap.add_argument("--endpoint", default="http://localhost:8080")
    ap.add_argument("--timeout", type=float, default=30.0)
    ap.add_argument("--csv-out", type=Path, default=None,
                    help="default: builds/<build>/features/features-"
                         "<split>.csv (gitignored, regenerated, not committed)")
    ap.add_argument("--block", choices=("features-log",), default="features-log")
    ap.add_argument("--from", dest="from_reports", type=Path, nargs="+", default=None,
                    help="print the block from reports this command wrote "
                         "earlier, without querying anything")
    ap.add_argument("--out", type=Path, required=False,
                    help="the committed JSON report (row/query counts, "
                         "per-label counts, column list, CSV sha256 and size, "
                         "deployed stamp) - required unless --from is used")
    args = ap.parse_args()

    if args.from_reports is not None:
        if args.split is not None:
            ap.error("--split has no effect with --from: the block lists every "
                     "report's own split; drop the flag")
        print(BLOCKS[args.block]([json.loads(p.read_text()) for p in args.from_reports]))
        return 0
    if args.split is None:
        ap.error("--split is required (train / validation / test, never inferred)")
    if args.out is None:
        ap.error("--out is required (the committed report; the CSV path is "
                 "separate and defaults under builds/)")

    build = args.build or builds.latest()
    app = Vespa(args.endpoint, timeout=args.timeout)
    if not app.healthy():
        print(f"no Vespa at {args.endpoint}", file=sys.stderr)
        return 1

    queries = builds.load_queries(build, args.split)
    labels = _labels(build, args.split)
    ids = sorted(queries)
    if args.limit:
        ids = ids[:args.limit]
        queries = {q: queries[q] for q in ids}
    total_pairs = sum(len(labels.get(q, {})) for q in ids)
    print(f"{builds.describe(build)}\n{len(ids):,} {args.split} queries, "
          f"{total_pairs:,} judged pairs, profile {PROFILE}, "
          f"{len(FEATURES)} match-features", file=sys.stderr)

    started = time.perf_counter()
    rows, retrieved_by_union = collect(app, queries, labels, out=sys.stderr,
        declared_inputs=profile_inputs(Path(__file__).resolve().parent / "app" / "schemas" / "product" / f"{PROFILE}.profile"))
    elapsed = time.perf_counter() - started
    print(f"\n{len(rows):,} rows in {elapsed:.1f}s "
          f"({retrieved_by_union:,} retrieved by the union arm)",
          file=sys.stderr)

    csv_path = args.csv_out or (build / "features" / f"features-{args.split}.csv")
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = ["query_id", "product_id", "label", "retrieved", *FEATURES]
    with csv_path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fieldnames)
        w.writeheader()
        w.writerows(rows)
    csv_bytes = csv_path.read_bytes()
    csv_sha256 = hashlib.sha256(csv_bytes).hexdigest()
    print(f"wrote {csv_path}: {len(csv_bytes):,} bytes, sha256 {csv_sha256}",
          file=sys.stderr)

    label_counts: dict[str, int] = {}
    for row in rows:
        label_counts[row["label"]] = label_counts.get(row["label"], 0) + 1

    report = {
        "split": args.split,
        "build": builds.meta(build)["build_id"],
        "profile": PROFILE,
        "queries": len(ids),
        "pairs": len(rows),
        "retrieved_by_union": retrieved_by_union,
        "label_counts": label_counts,
        "columns": fieldnames,
        "csv_path": repo_relative(csv_path),
        "csv_sha256": csv_sha256,
        "csv_bytes": len(csv_bytes),
        **deployed.stamp(),
        "host": hostinfo.collect(),
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2) + "\n")
    print(f"wrote {args.out}", file=sys.stderr)

    print(BLOCKS[args.block]([report]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
